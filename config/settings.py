def hotes_autorises(valeur):
    """`"a.com, b.com"` → `["a.com", "b.com"]`.

    Sans le `strip`, l'espace après la virgule produisait `" b.com"`, qui ne
    correspond à aucun en-tête `Host` : le second domaine répondait 400 sans
    que la configuration ait l'air fausse. Les entrées vides sont écartées.
    """
    return [hote.strip() for hote in (valeur or "").split(",") if hote.strip()]


